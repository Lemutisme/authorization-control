"""Write table data and publication figures from recomputed experimental results."""
import csv
import json
from pathlib import Path

NAMES={'luna':'GPT-6 Luna','haiku':'Claude Haiku 5.5','deepseek':'DeepSeek-V4.1-Flash',
       'lumen_qwen':'Qwen3.8-Flash-Next','lumen_glm':'GLM-5.3','glm':'GLM-5.3-Flash',
       'lumen_beam':'Beam 1.0','minimax':'MiniMax-M3.1-Flash'}

def build(output):
    output=Path(output);tables=output/'tables';figures=output/'figures'
    tables.mkdir(parents=True,exist_ok=True);figures.mkdir(parents=True,exist_ok=True)
    reports={name:json.loads((output/(name+'.json')).read_text())for name in ['faults','matched','models','history']}
    def csv_table(name,rows):
        fields=list(dict.fromkeys(k for row in rows for k in row))
        with (tables/(name+'.csv')).open('w',newline='') as stream:
            writer=csv.DictWriter(stream,fieldnames=fields);writer.writeheader();writer.writerows(rows)
    fault=reports['faults']['table'];rows=[]
    for kind in ['M1','M2','M3']:
        rows.append({'fault':kind,**{feedback:row['by_fault'][kind]['wrong']for feedback,row in fault.items()},'n':fault['F0']['by_fault'][kind]['n']})
    csv_table('fault-injection',rows)
    csv_table('full-episode-studies',reports['history']['groups'])
    csv_table('construction',[{'representation':name,**value}for name,value in reports['history']['construction'].items()])
    csv_table('repeated-probes',reports['history']['repeated_probes'])
    csv_table('policy-probes',[reports['history']['policy_probes']])
    for panel in ['full','common']:
        for role in ['actor','update']:csv_table('models-'+panel+'-'+role,reports['models']['counts'][panel][role])
    for name in ['status','reminders']:csv_table(name,reports['models']['counts'][name])
    matched=[]
    for panel,group in reports['matched']['groups'].items():
        for metric,value in group['metrics'].items():
            for arm,counts in value['arms'].items():matched.append({'panel':panel,'metric':metric,'arm':arm,**counts})
    csv_table('matched-inputs',matched)
    (tables/'all-results.json').write_text(json.dumps(reports,indent=2)+'\n')
    tex=['% Generated by python -m pipeline figures; counts are read from recomputed records.','\\begin{tabular}{lrrrrrr}','Fault & Value/retry & Value & Argument & Opaque & Ask & N \\\\','\\hline']
    for row in rows:tex.append(' & '.join(str(row[k])for k in ['fault','F0','F1','F2','F3','F4','n'])+' \\\\')
    tex.append('\\end{tabular}');(tables/'fault-injection.tex').write_text('\n'.join(tex)+'\n')
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    plt.rcParams.update({'font.size':9,'pdf.fonttype':42,'ps.fonttype':42,'axes.spines.top':False,'axes.spines.right':False})
    def save(fig,name):
        fig.savefig(figures/(name+'.pdf'),bbox_inches='tight');fig.savefig(figures/(name+'.svg'),bbox_inches='tight');plt.close(fig)
    fig,ax=plt.subplots(figsize=(5.2,2.7));labels=['Value + retry','Value only','Argument','Opaque','Ask user']
    wrong=[fault[f]['wrong_selected_effect']for f in fault];unauthorized=[fault[f]['unauthorized_effect']for f in fault]
    ax.bar(labels,unauthorized,color='#b9252a',label='Unauthorized effects')
    ax.bar(labels,[a-b for a,b in zip(wrong,unauthorized)],bottom=unauthorized,color='#edb0b2',label='Other deviations')
    for i,n in enumerate(wrong):ax.text(i,n+1,str(n)+'/130',ha='center',fontsize=8)
    ax.set(ylabel='Episodes',ylim=(0,100));ax.tick_params(axis='x',rotation=15);ax.legend(frameon=False);save(fig,'fault-feedback')
    rows=reports['models']['counts']['common']['actor'];order=list(NAMES)
    fig,axes=plt.subplots(1,2,figsize=(8,3.4),sharey=True)
    for axis,direction,field,title in [(axes[0],'correction','correct','Correct permission'),(axes[1],'corruption','wrong','Wrong permission')]:
        for i,model in enumerate(order):
            cell={r['feedback']:r for r in rows if r['model']==model and r['direction']==direction}
            start=cell['value_free'][field];end=cell['value_stating'][field]
            color='#16754d' if direction=='correction' else '#b9252a'
            axis.plot([start,end],[i,i],color=color,lw=2);axis.scatter([start],[i],facecolors='white',edgecolors=color,zorder=3);axis.scatter([end],[i],color=color,zorder=3)
        axis.set(title=title,xlim=(-1,33),xlabel='Effects, of 31 tasks',yticks=range(len(order)),yticklabels=[NAMES[m]for m in order])
    axes[0].invert_yaxis()
    from matplotlib.lines import Line2D
    handles=[Line2D([],[],marker='o',linestyle='none',markerfacecolor='white',color='black',label='Value withheld'),
             Line2D([],[],marker='o',linestyle='none',color='black',label='Value stated')]
    fig.legend(handles=handles,loc='upper center',bbox_to_anchor=(.5,1.06),ncol=2,frameon=False)
    save(fig,'model-feedback')
    rows=reports['models']['counts']['common']['update'];order=[m for m in NAMES if m!='minimax']
    fig,axes=plt.subplots(1,2,figsize=(8,3.1),sharey=True)
    for axis,panel,title,color in [(axes[0],'honest_fault','Correct calls reopened, of 23','#16754d'),(axes[1],'attack','Harmful calls admitted, of 106','#b9252a')]:
        for i,model in enumerate(order):
            cell={r['visible']:r for r in rows if r['model']==model and r['panel']==panel}
            a=cell['False']['admitted'];b=cell['True']['admitted']
            axis.plot([a,b],[i,i],color=color,lw=2);axis.scatter([a],[i],facecolors='white',edgecolors=color,zorder=3);axis.scatter([b],[i],color=color,zorder=3)
        axis.set(title=title,xlabel='Calls',yticks=range(len(order)),yticklabels=[NAMES[m]for m in order],xlim=(-.5,23 if panel=='honest_fault' else 5))
    axes[0].invert_yaxis()
    handles=[Line2D([],[],marker='o',linestyle='none',markerfacecolor='white',color='black',label='Proposal hidden'),Line2D([],[],marker='o',linestyle='none',color='black',label='Proposal visible')]
    fig.legend(handles=handles,loc='upper center',bbox_to_anchor=(.5,1.07),ncol=2,frameon=False);save(fig,'model-updates')
    rows=reports['models']['counts']['status'];fig,ax=plt.subplots(figsize=(4.5,2.7))
    for i,model in enumerate(['luna','haiku']):
        values={r['arm']:r['correct']for r in rows if r['model']==model and r['panel']=='honest_reopened'}
        for offset,arm,color,label in [(-.18,'call_reviewed','#aeb9c5','Reviewed'),(.18,'permission_status','#16754d','Now permitted')]:
            value=values[arm];ax.bar(i+offset,value,width=.32,color=color,label=label if i==0 else None);ax.text(i+offset,value+.2,str(value),ha='center',fontsize=8)
    ax.set(xticks=[0,1],xticklabels=[NAMES['luna'],NAMES['haiku']],ylabel='Correct effects, of 18',ylim=(0,21));ax.legend(frameon=False);save(fig,'repair-status')
    print('Wrote tables and PDF/SVG figures to '+str(output.resolve()))
